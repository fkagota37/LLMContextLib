import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import * as core from '../../src/index.js';
import { LuceneTermCollection } from '../../adapters/lucene/index.js';

interface SourceType {
  readonly type: string;
  readonly isEnum: boolean;
  readonly members: readonly { readonly kind: string; readonly signature: string; readonly value?: number }[];
}

const path = process.argv[2];
assert(path, 'Pass the JSON generated by inventory-source-api.ps1.');
const source = JSON.parse(readFileSync(path, 'utf8').replace(/^\uFEFF/, '')) as SourceType[];
const target = { ...core, LuceneTermCollection } as Record<string, unknown>;
const rows = source.filter((entry) => entry.isEnum).flatMap(({ type, members }) => {
  const enumName = type.split('.').at(-1)!;
  const sourceFields = members.filter(({ kind }) => kind === 'Field').map(({ signature, value }) => {
    assert(Number.isInteger(value), signature);
    return { member: signature.split(' ').at(-1)!, ordinal: value };
  });
  const values = target[enumName];
  assert(values && typeof values === 'object', `Missing public enum ${enumName}.`);
  assert.deepEqual(Object.keys(values).sort(), sourceFields.map(({ member }) => member).sort(), enumName);
  return sourceFields.map(({ member, ordinal }) => {
    const encoding = (values as Record<string, unknown>)[member];
    assert.equal(encoding, member, `${enumName}.${member}`);
    return { type, member, sourceOrdinal: ordinal, targetValue: encoding };
  });
});
assert.equal(new Set(rows.map(({ type }) => type)).size, 11);
for (const row of rows) console.log(JSON.stringify(row));
