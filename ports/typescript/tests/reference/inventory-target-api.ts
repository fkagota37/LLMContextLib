  ILLMContextViewDefinition: 'view-contracts.spec.ts; supported-contracts.spec.ts',
  LLMContextFactory: 'supported-contracts.spec.ts; configuration-contracts.spec.ts',
  LLMContextFactoryBuilder: 'supported-contracts.spec.ts; configuration-contracts.spec.ts; reference/verify-packages.mjs',
  LLMContextOptions: 'reference/verify-options.ts; supported-contracts.spec.ts; configuration-contracts.spec.ts',
  ContextExecutionOptions: 'reference/verify-options.ts; configuration-contracts.spec.ts; lifecycle-contracts.spec.ts',
  DeferredIndexingOptions: 'reference/verify-options.ts; configuration-contracts.spec.ts; lifecycle-contracts.spec.ts',
  PartitionedContextIndexOptions: 'reference/verify-options.ts; configuration-contracts.spec.ts; reference/verify-partitions.ts',
  BitFasterTermMemoOptions: 'configuration-contracts.spec.ts; reference/verify-memo.ts; reference/verify-adapter-workers.ts',
  LuceneExecutionExtensions: 'configuration-contracts.spec.ts; lifecycle-contracts.spec.ts; reference/verify-adapter-workers.ts',
  BitFasterExecutionExtensions: 'configuration-contracts.spec.ts; lifecycle-contracts.spec.ts; reference/verify-adapter-workers.ts',
